const _: () = assert!(FONT.len() == 64);

pub fn glyph(byte: u8) -> &'static [u8; 7] {
    let upper = byte.to_ascii_uppercase();
    if (0x20..=0x5f).contains(&upper) {
        &FONT[(upper - 0x20) as usize]
    } else {
        &FONT[0]
    }
}

/// Width in pixels of `text` at the given scale, excluding the trailing gap.
pub fn text_width(text: &str, scale: u64) -> u64 {
    let count = text.len() as u64;
    if count == 0 {
        0
    } else {
        count * CELL_WIDTH * scale - scale
    }
}
